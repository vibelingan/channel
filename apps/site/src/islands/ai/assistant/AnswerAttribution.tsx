import { safePublicChatLink } from '../../../components/chat/public-link';

/** Attribution is separate from the answer; source titles remain available on demand. */
export function AnswerAttribution({
  citations = [],
}: { citations?: Array<{ title: string; url?: string }> }) {
  const origin = typeof window === 'undefined' ? 'https://preview.invalid' : window.location.origin;
  return (
    <aside
      aria-label="Answer information"
      className="mx-3 mt-1 flex flex-wrap items-start gap-x-2 text-[11px] leading-4 text-slate-600"
    >
      <span>Generated by SupplyChainsAI Assistant</span>
      {citations.length > 0 && (
        <details>
          <summary className="cursor-pointer underline underline-offset-2">Sources</summary>
          <ul className="mt-1 space-y-1 break-words">
            {citations.map((citation, index) => {
              const href = safePublicChatLink(citation.url, origin);
              return (
                <li key={`${citation.title}-${index}`}>
                  {href ? (
                    <a href={href} target="_blank" rel="noopener noreferrer" className="underline">
                      {citation.title} ↗
                    </a>
                  ) : (
                    citation.title
                  )}
                </li>
              );
            })}
          </ul>
        </details>
      )}
    </aside>
  );
}
