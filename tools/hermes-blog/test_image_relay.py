import io
import json
import os
import subprocess
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch
import image_relay as images


class ImageTransfer(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.source = self.root / 'generated'; self.source.mkdir()
        self.file = self.source / 'original.png'
        self.bytes = b'\x89PNG\r\n\x1a\n' + b'original generated bytes'
        self.file.write_bytes(self.bytes)
        self.config = {'imageSourceRoot': str(self.source), 'imageOutbox': str(self.root/'outbox'), 'imageInbox': str(self.root/'inbox')}
        self.payload = {'documentId': 203, 'images': [{'filePath': str(self.file), 'alt': 'Headphones and a notebook', 'placement': {'type':'start'}}]}
        self.addCleanup(patch.stopall)
        patch('image_relay.connect_kb', return_value=object()).start()
        patch('image_relay.fetch_document', return_value={'id':203,'workspace_id':2}).start()

    def frame(self, manifest, data=None):
        return io.BytesIO(images.canonical(manifest)+b'\n'+(self.bytes if data is None else data))

    def test_actual_files_round_trip_replay_and_permissions(self):
        sent, manifest = images.prepare(self.config,self.payload)
        received = images.receive(self.config,self.frame(manifest))
        self.assertEqual((sent/'job.json').read_bytes(),(received/'job.json').read_bytes())
        file = received/manifest['images'][0]['fileName']
        self.assertEqual(file.read_bytes(),self.bytes)
        self.assertEqual(file.stat().st_mode & 0o777,0o600)
        self.assertEqual(received.stat().st_mode & 0o777,0o700)
        self.assertEqual(images.receive(self.config,self.frame(manifest)),received)
        self.assertEqual(len(list(received.glob('*.png'))),1)

    def test_truncation_wrong_hash_extra_bytes_and_oversize_rejected(self):
        _, manifest = images.prepare(self.config,self.payload)
        for data in [self.bytes[:-1],b'x'*len(self.bytes),self.bytes+b'extra']:
            with self.subTest(data=len(data)):
                with self.assertRaises(ValueError): images.receive(self.config,self.frame(manifest,data))
        manifest['images'][0]['byteSize']=images.MAX_IMAGE+1
        with self.assertRaises(ValueError): images.receive(self.config,self.frame(manifest))
        with self.assertRaises(ValueError): images.receive(self.config,io.BytesIO(b'x'*(images.MAX_HEADER+2)))

    def test_only_owned_generated_files_and_unique_images(self):
        outside=self.root/'other-app.png';outside.write_bytes(self.bytes)
        for path in [outside,self.source/'symlink.png']:
            if path.name=='symlink.png':path.symlink_to(self.file)
            bad={'documentId':203,'images':[{**self.payload['images'][0],'filePath':str(path)}]}
            with self.assertRaises(ValueError):images.prepare(self.config,bad)
        bad={**self.payload,'images':self.payload['images']*2}
        with self.assertRaises(ValueError):images.prepare(self.config,bad)
        self.file.unlink();self.file.symlink_to(outside)
        with self.assertRaises(ValueError):images.prepare(self.config,self.payload)

    def test_dispatcher_rejects_shell_and_file_transfer_commands(self):
        dispatcher=Path(__file__).with_name('dispatch_relay.py')
        for command in ['sh','channel-blog-images; id','scp -t /tmp/file','channel-blog-submit extra','']:
            result=subprocess.run(['/usr/bin/python3',str(dispatcher),'--config',str(self.root/'binding.json')],env={**os.environ,'SSH_ORIGINAL_COMMAND':command},capture_output=True)
            self.assertNotEqual(result.returncode,0)

if __name__=='__main__':unittest.main()
